/* =========================================================
   7. 복합성향 가져오기
========================================================= */

export function getCombinationInfo(
  primaryType,
  secondaryType
) {
  if (
    !primaryType ||
    !secondaryType ||
    primaryType === secondaryType
  ) {
    return null;
  }


  const key =
    `${primaryType}-${secondaryType}`;


  return (
    COMBINATION_INFO[
      key
    ] || null
  );
}


/* =========================================================
   8. 복합성향 강도

   점수 차이
   0점      → 동급 복합성향
   1점      → 강한 복합성향
   2~3점    → 균형 복합성향
   4점 이상 → 뚜렷한 주성향
========================================================= */

export function getCombinationStrength(
  primaryScore,
  secondaryScore
) {
  const primary =
    Number(
      primaryScore
    ) || 0;


  const secondary =
    Number(
      secondaryScore
    ) || 0;


  const difference =
    Math.abs(
      primary -
      secondary
    );


  if (
    difference === 0
  ) {
    return {
      key:
        "equal",

      label:
        "동급 복합성향",

      difference,

      description:
        "두 성향이 거의 동일한 수준으로 나타나는 복합성향입니다.",
    };
  }


  if (
    difference === 1
  ) {
    return {
      key:
        "strong-mix",

      label:
        "강한 복합성향",

      difference,

      description:
        "주성향과 보조성향이 매우 가깝게 나타나는 강한 복합성향입니다.",
    };
  }


  if (
    difference <= 3
  ) {
    return {
      key:
        "balanced",

      label:
        "균형 복합성향",

      difference,

      description:
        "주성향을 중심으로 보조성향의 특징도 함께 나타나는 균형형입니다.",
    };
  }


  return {
    key:
      "primary",

    label:
      "뚜렷한 주성향",

    difference,

    description:
      "주성향의 특징이 비교적 뚜렷하게 나타나는 유형입니다.",
  };
}


/* =========================================================
   9. 성향 이름 → KEY 변환
========================================================= */

export function getTypeKeyFromLabel(
  value
) {
  if (
    !value
  ) {
    return null;
  }


  if (
    TYPE_INFO[
      value
    ]
  ) {
    return value;
  }


  const normalized =
    String(
      value
    ).trim();


  const entry =
    Object.entries(
      TYPE_INFO
    ).find(
      ([
        ,
        info,
      ]) =>
        info.label ===
        normalized
    );


  return entry
    ? entry[0]
    : null;
}
