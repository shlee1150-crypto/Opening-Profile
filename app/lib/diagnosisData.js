/* =========================================================
   복합성향 가져오기
========================================================= */

export function getCombinationInfo(
  primaryType,
  secondaryType
) {
  if (
    !primaryType ||
    !secondaryType ||
    primaryType === secondaryType
  ) {
    return null;
  }

  return (
    COMBINATION_INFO[
      `${primaryType}-${secondaryType}`
    ] || null
  );
}


/* =========================================================
   복합성향 강도
========================================================= */

export function getCombinationStrength(
  primaryScore,
  secondaryScore
) {
  const difference =
    Math.max(
      0,
      Number(primaryScore || 0) -
        Number(secondaryScore || 0)
    );

  if (difference === 0) {
    return {
      label:
        "동급 복합성향",

      description:
        "두 가지 성향이 거의 동일한 수준으로 나타나는 복합형입니다.",
    };
  }

  if (difference === 1) {
    return {
      label:
        "강한 복합성향",

      description:
        "메인 성향과 보조 성향이 매우 가깝게 나타나 두 특성이 함께 강하게 작용합니다.",
    };
  }

  if (
    difference === 2 ||
    difference === 3
  ) {
    return {
      label:
        "균형 복합성향",

      description:
        "메인 성향이 중심을 잡고 보조 성향이 의사결정 방식을 균형 있게 보완합니다.",
    };
  }

  return {
    label:
      "뚜렷한 주성향",

    description:
      "메인 성향이 비교적 뚜렷하고 보조 성향은 특정 상황에서 의사결정을 보완합니다.",
  };
}


/* =========================================================
   DB에 저장된 한글 유형 → 내부 키
========================================================= */

export function getTypeKeyFromLabel(
  label
) {
  return (
    Object.keys(
      TYPE_INFO
    ).find(
      (key) =>
        TYPE_INFO[key].label === label
    ) || null
  );
}
